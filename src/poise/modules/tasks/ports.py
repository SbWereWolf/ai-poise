class TaskUnitOfWork(Protocol):
    def capture(self, read_set: TaskReadSet) -> TaskInputs: ...
    def require_inputs(self, inputs: TaskInputs) -> None: ...
    def prepare_change(self, inputs: TaskInputs, change: Change) -> object: ...
    def prepare_newborn(self, inputs: TaskInputs, newborn: object, config_hash: str) -> str: ...
    def prepare_newborn_create(self, newborn: object, config_hash: str) -> str: ...
    def prepare_action_receipt(self, request_id: str, digest: str, result: dict) -> str: ...
    def prepare_sprint(self, record: dict) -> object: ...
    def capture_sprint(self, sprint_id: str | None, actor: str, task_ids: tuple = (),
                       creation_requests: tuple = ()) -> SprintInputs: ...
    def capture_sprint_view(self, sprint_id: str | None, actor: str, view: str) -> SprintInputs: ...
    def require_sprint(self, inputs: SprintInputs) -> None: ...
    def prepare_claim_changes(self, inputs: TaskInputs, changes: tuple[Change, ...]) -> tuple[object, ...]: ...
    def prepare_execution(self, inputs: TaskInputs, task_id: str, data: dict) -> str: ...
    def prepare_evidence(self, receipt: dict) -> str: ...
    def timeout_history(self, profile: object) -> dict: ...
    def prepare_action(self, inputs: TaskInputs, task_id: str, stage: str, iteration: int, data: dict) -> object: ...
    def prepare_progression_entry(self, kind: str, data: dict) -> object: ...
    def restore_progression_request(self, raw: object, request_id: str, digest: str) -> dict | None: ...
    def prepare_stage_contract_change(self, inputs: TaskInputs, change: Change, audit: dict) -> object: ...
    def restore_stage_contract_receipt(self, raw: object, task_id: str, request_id: str, intent: dict) -> dict: ...
    def prepare_restart_event(self, reason: str, authorization: object) -> str: ...
    def prepare_result(self, report: dict) -> object: ...
    def prepare_cycle_release(self, inputs: TaskInputs, actor: str, task_id: str) -> object | None: ...
    def prepare_release_receipt(self, intent: dict, actor: str, result: dict) -> str: ...
    def prepare_ownership_reconciliation(self, proof: dict) -> str: ...
    def prepare_duplicate_newborn(self, newborn: NewbornTask, config_hash: str, parent_id: str) -> tuple[str, str]: ...
    def prepare_sprint_receipt(self, result: dict) -> str: ...
    def restore_sprint_receipt(self, raw: str) -> dict: ...
    def prepare_task_creation(self, task: Task, metadata: dict) -> object: ...
    def new_promotion_source(self, newborn: NewbornTask, config_hash: str) -> object: ...
    def existing_promotion_source(self, inputs: TaskInputs, task_id: str) -> object: ...
    def prepare_promotion(self, source: object, task: Task, metadata: dict) -> object: ...
    def prepare_requirements_context(self, inputs: TaskInputs, task_id: str, snapshot: dict, agreement: dict) -> object: ...
    def prepare_requirements_patch(self, receipt: object, context: dict) -> object | None: ...
    def newborn_member_fact(self, inputs: SprintInputs, newborn: NewbornTask, metadata: str) -> object: ...
    def prepared_member_fact(self, inputs: SprintInputs, prepared: object) -> object: ...
    def member_fact_with_execution(self, fact: object, execution: str) -> object: ...
    def creation_member_fact(self, prepared: object, inputs: SprintInputs) -> object: ...
    def promotion_member_fact(self, inputs: SprintInputs, candidate: dict) -> object: ...
    def prepare_membership(self, inputs: TaskInputs, task_id: str, expected_sprint: str | None,
                           target_sprint: str | None, version: int) -> object: ...
    def prepare_membership_fact(self, fact: object, expected_sprint: str | None,
                                target_sprint: str | None, version: int) -> object: ...
    def membership_member_fact(self, inputs: SprintInputs, prepared: object) -> object: ...
    actions: ActionRepository
    accounting_cycles: object
    preparation: PreparationRepository
    sprints: "SprintRepository"
    tasks: TaskRepository
    execution: ExecutionRepository
    evidence: EvidenceRepository
    ownership: object
    work_packets: WorkPacketRepository
    artifacts: ArtifactLinkRepository
    integration_scopes: IntegrationScopeRepository
    def __enter__(self) -> TaskUnitOfWork: ...
    def __exit__(self, exc_type, exc, traceback) -> bool: ...


