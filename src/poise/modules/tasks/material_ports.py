"""Ports for permanent Task comments and their original file materials."""
from typing import Protocol


class TaskMaterialsRepository(Protocol):
    def request(self, task_id: str, request_id: str) -> dict | None: ...
    def prepare(self, task_id: str, value: dict) -> None: ...
    def commit(self, task_id: str, value: dict) -> None: ...


class TaskMaterialQueries(Protocol):
    def materials_request(self, task_id: str, request_id: str) -> tuple: ...
    def materials_view(self, task_id: str) -> dict: ...
    def material_attachment(self, task_id: str, attachment_id: str) -> tuple: ...


class TaskMaterialFiles(Protocol):
    def require_configured(self) -> None: ...
    def prepare(self, intent: object) -> tuple: ...
    def publish(self, prepared: tuple) -> None: ...
    def discard(self, task_id: str, records: list[dict]) -> None: ...
    def read(self, task_id: str, record: dict) -> bytes: ...
