"""Read-only instruction sources; no Task, caller or execution dependencies."""
from typing import Protocol

from .catalog import SkillCatalog
from .instructions import MaterialSpec


class InstructionSource(Protocol):
    def project_context(self, config_path: str, checkout: str) -> dict: ...
    def catalogue_metadata(self) -> SkillCatalog: ...
    def policy_document(self, path: str) -> tuple[dict, str]: ...
    def existing_rule_paths(self, checkout: str, paths: list[str]) -> list[tuple[str, list[str]]]: ...
    def observe_materials(self, context: dict, specs: list[MaterialSpec]) -> list[dict]: ...
