"""Task-owned transfer persistence and existing-owner effect boundaries."""
from typing import Protocol, Any

from .handoff import StageHandoffState


class HandoffRepository(Protocol):
    def save_prepared(self, actor: str, state: StageHandoffState,
                      encoded: str, expected_revision: int) -> None: ...


class HandoffEffects(Protocol):
    def digest(self, value: object) -> str: ...
    def require_owner(self, task_id: str) -> dict: ...
    def prepare_verification(self, args: dict) -> Any: ...
    def execute_verification(self, prepared: Any) -> dict: ...
    def recovered_verification(self, state: StageHandoffState) -> dict | None: ...
    def require_unverified_source(self, state: StageHandoffState) -> None: ...
    def source(self, task_id: str) -> dict: ...
    def require_verified_source(self, state: StageHandoffState) -> None: ...
    def context(self, task_id: str) -> dict: ...
    def progression_context(self, state: StageHandoffState) -> dict: ...
    def require_progression_resume(self, state: StageHandoffState) -> None: ...
    def advance(self, state: StageHandoffState) -> dict: ...
    def original_release(self, intent: dict) -> dict | None: ...
    def release(self, intent: dict) -> dict: ...
    def pending(self, task_id: str) -> object: ...
