"""Boundaries of proxy persistence, native execution and the assigned notifier."""
from typing import ContextManager, Protocol

from .domain import ProxyState


class ProxyJournal(Protocol):
    response_path: str
    def locked(self) -> ContextManager: ...
    def load(self) -> ProxyState | None: ...
    def save(self, state: ProxyState, *, replayed: bool = False) -> dict: ...


class HandoffPort(Protocol):
    def prepare(self) -> None: ...
    def run(self, packet: dict) -> dict: ...


class NotificationPort(Protocol):
    def prepare(self) -> None: ...
    def send(self, recipient: dict, prompt: str, caller: str) -> dict: ...
    def close(self) -> None: ...
