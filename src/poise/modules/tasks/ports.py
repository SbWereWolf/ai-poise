class TaskSourcesChanged(VersionConflict):
    def __init__(self, current: TaskInputs):
        super().__init__('Task preparation source changed; repeat the request')
        self.current = current


class TaskInputs(Protocol):
    def exists(self, task_id: str) -> bool: ...
    def artifact_records(self, task_id: str) -> list[dict]: ...
    def sprint_eligibility(self, task_id: str) -> tuple[dict | None, dict]: ...
    def action_binding(self, task_id: str, stage: str, iteration: int) -> ActionBinding: ...
    def membership_snapshot(self, task_id: str) -> dict: ...
    def criteria_submission_guard(self, task: Task, actor: str, report: dict) -> int: ...
    def work_packet(self, task_id: str, stage: str, iteration: int) -> str | None: ...
    def replay_progress(self, task_id: str, request_id: str) -> dict | None: ...
    def accepted_replay_sources(self, task_id: str) -> dict | None: ...
    def progression_view(self, task_id: str, request_id: str | None = None) -> dict | None: ...
    def progression_request(self, task_id: str, request_id: str, digest: str) -> dict | None: ...
    def begin_progression(self, task_id: str, actor: str, request_id: str, digest: str,
                         target_stage: str | None) -> tuple[dict, dict | None]: ...
    def ownership_event_suffix(self, task_id: str, after_version: int, through_version: int) -> tuple[str, ...]: ...
    def verified_ownership_history(self, task_id: str, stage_id: str, iteration: int,
                                   digest: str, through_version: int) -> dict | None: ...
    def cancellation_recovery_point(self, task_id: str, version: int) -> TaskState: ...
    def empty_rework_recovery_point(self, task_id: str, version: int, report: dict,
                                    transition_event: str) -> EmptyReworkRecoveryPoint: ...
    def evidence(self, task_id: str) -> list: ...
    def read_duplicate_family(self, task_id: str) -> dict | None: ...
    def state(self, task_id: str) -> TaskState: ...
    def task(self, task_id: str) -> Task: ...
    def newborn(self, task_id: str) -> NewbornTask: ...
    def execution(self, task_id: str) -> tuple[dict, int] | None: ...
    def required_execution(self, task_id: str) -> tuple[dict, int]: ...
    def review_identity(self, task_id: str, *, include_unsubmitted: bool = False) -> dict | None: ...
    def ownership(self, actor: str) -> OwnershipSnapshot: ...
    def worktree_required(self, task_id: str) -> bool: ...
    def sprint(self, sprint_id: str) -> dict | None: ...
    def allocate(self, intent: dict, policy: TaskIdPolicy | None, reserved_ids: tuple = ()) -> Allocation: ...
    def creation_receipt(self, request_id: str) -> object | None: ...
    def action_run(self, task_id: str, stage: str, iteration: int) -> dict | None: ...
    def restart_context(self, task_id: str) -> dict: ...
    def restarted_registry(self, task_id: str) -> CheckRegistry: ...
    def restarted_feedback(self, task_id: str) -> FeedbackBook: ...
    def restarted_evidence(self, task_id: str) -> EvidenceBook: ...


