"""Explicit registry semantics and immutable Task snapshot storage boundaries."""
from typing import Protocol
from .domain import RequirementsRegistry


class RegistrySnapshotProvider(Protocol):
    def registry(self) -> RequirementsRegistry: ...
    def prepare_identity(self, expected: dict) -> object: ...
    def require_same(self, identity: object) -> None: ...


class TaskRequirementsSnapshots(Protocol):
    def exists(self, task_id: str) -> bool: ...
    def create(self, task_id: str, snapshot: dict, agreement: dict) -> None: ...
    def read(self, task_id: str) -> dict: ...
