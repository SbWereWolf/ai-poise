"""Durable attempt state and external preparation effects."""
from typing import Protocol
from .domain import PreparationAttempt


class PreparationRepository(Protocol):
    def latest(self, task_id: str) -> PreparationAttempt | None: ...
    def by_request(self, task_id: str, request_id: str) -> PreparationAttempt | None: ...
    def save(self, actor: str, state: PreparationAttempt, expected_revision: int) -> PreparationAttempt: ...


class PreparationEffects(Protocol):
    def capture_configuration(self, attempt: PreparationAttempt) -> dict: ...
    def publish_inputs(self, material: dict) -> None: ...
    def execute_operations(self, material: dict) -> None: ...
    def save_capture(self, material: dict) -> dict: ...
    def recover_capture(self, attempt: PreparationAttempt) -> dict: ...
    def confirm_capture(self, capture: dict) -> dict: ...
    def publish_receipt(self, report: dict) -> tuple[dict, list[dict]]: ...
