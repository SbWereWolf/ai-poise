"""Storage and admission ports for complete tool results."""
from typing import Protocol


class ResultStore(Protocol):
    def address(self, request_id: str) -> str: ...
    def capture(self, request: dict, *, prepare=None, source_text: str | None = None) -> dict: ...
    def load(self, address: str) -> dict: ...
    def sources(self, record: dict) -> dict: ...
    def source(self, record: dict, channel: str) -> 'StoredSource': ...
    def latest(self) -> dict: ...
    def validate_prepared(self, record: dict) -> None: ...
    def expanded(self, record: dict) -> str: ...


class StoredSource(Protocol):
    metadata: dict
    def lines(self): ...
    def bytes(self, start: int, end: int) -> bytes: ...
    def boundary(self, offset: int) -> bool: ...


class ResultPlacement(Protocol):
    def prepare(self, paths: list[str]) -> None: ...


class UnknownInputRegistry(Protocol):
    def register(self, observation: dict) -> dict: ...


class UnknownInputDispatcher(Protocol):
    def submit(self, observation: dict) -> None: ...
