from __future__ import annotations

from typing import ContextManager, Protocol

from .domain import BackupCopy, BackupEntry


class TaskDatabaseBackups(Protocol):
    @property
    def filename_source(self) -> str: ...

    def list_entries(self) -> tuple[BackupEntry, ...]: ...

    def create_copy(self, name: str) -> BackupCopy: ...

    def restore_copy(self, name: str) -> None: ...

    @property
    def project_identity(self) -> str: ...

    def locked(self) -> ContextManager: ...

    def archive_exists(self, name: str) -> bool: ...

    def archive_digest(self, name: str) -> str: ...

    def delete_archive(self, name: str) -> bool: ...

    def grant_names(self) -> tuple[str, ...]: ...

    def grant_state(self, name: str) -> tuple[dict | None, bool]: ...

    def publish_grant(self, name: str, grant: dict) -> None: ...

    def delete_grant(self, name: str) -> None: ...

    def operator_identity(self) -> str: ...
