from typing import Protocol
from .domain import HookDefinition


class HookRepository(Protocol):
    def relocate(self,target: dict,installation: dict,request_id: str) -> dict: ...
    def install(self,request_id: str,expected_revision: str | None,definition: HookDefinition) -> dict: ...
    def reconcile(self,request_id: str,expected_revision: str,definition: HookDefinition,previous_installation_id: str,live_definition_path: str) -> dict: ...


class HandlerExecutor(Protocol):
    def execute(self, handler: dict, packet: dict, directory, *, resources: dict) -> tuple[dict, dict | None]: ...
    def launch(self, handler: dict, packet: dict, directory, delivery_path) -> None: ...


class DispatchDeliveryStore(Protocol):
    def read(self, path) -> dict: ...
    def begin_invocation(self, path, planned: dict) -> dict: ...
    def update_invocation(self, path, invocation_id: str, **changes) -> dict: ...
    def save_response(self, path, response: dict, *, failed: bool) -> dict: ...
    def invocation_directory(self, path, invocation_id: str): ...
    def save_input(self, directory, packet: dict) -> None: ...
