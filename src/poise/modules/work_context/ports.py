"""Working context uses the existing native session, reader and observation owners."""
from typing import Protocol
from .domain import CheckpointState, ContextScope


class ContextSession(Protocol):
    scope: ContextScope
    def context(self) -> int: ...
    def advance(self) -> int: ...
    def revalidate(self, generation: int) -> None: ...


class CheckpointStore(Protocol):
    ref: str
    def load(self) -> CheckpointState: ...
    def save(self, value: dict, generation: int) -> None: ...
    def clear(self, generation: int) -> None: ...


class ContextFacts(Protocol):
    def observe(self) -> dict: ...
