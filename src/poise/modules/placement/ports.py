"""Narrow placement I/O boundaries; no Task or infrastructure dependency."""
from typing import ContextManager, Protocol


class PlacementWorkspace(Protocol):
    path: str

    def locked(self, operation: str) -> ContextManager: ...
    def read(self) -> bytes | None: ...
    def baseline(self) -> list[str]: ...
    def encode(self, document: dict) -> bytes: ...
    def write(self, content: bytes) -> None: ...
    def confirm(self) -> None: ...
    def missing(self) -> bool: ...


class CurrentPlacementOwners(Protocol):
    def current(self, kinds: set[str]) -> dict: ...
