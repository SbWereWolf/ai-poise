"""One selected workspace supplies actual process and filesystem observations."""
from typing import ContextManager, Protocol

from .domain import IndexPolicy


class IndexWorkspace(Protocol):
    policy: IndexPolicy
    checkout: str
    database: str

    def hold(self) -> ContextManager: ...
    def head(self) -> str: ...
    def database_exists(self) -> bool: ...
    def run(self, operation: str, arguments: tuple[str, ...]) -> dict: ...
    def health_document(self, execution: dict) -> object: ...
    def recovery(self, operation: str) -> str: ...
