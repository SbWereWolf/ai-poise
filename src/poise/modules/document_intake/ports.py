"""Application-facing intake ports; adapters retain their real I/O ownership."""
from pathlib import Path
from typing import Protocol
from .domain import PreparedContent, ReadScope


class ContentSource(Protocol):
    def select(self, checkout: Path, item: dict, policy: dict) -> PreparedContent: ...


class NativeAuthority(Protocol):
    def resolve_episode(self, session_id: str, owned_episode: dict | None) -> dict: ...
    def observe(self, episode: dict) -> dict: ...
    def verify_end_receipt(self, receipt: dict) -> bool: ...


class IntakeRegistry(Protocol):
    def context(self, scope: ReadScope) -> tuple[int, dict]: ...
    def preview_batch(self, scope: ReadScope, prepared: list) -> tuple[int, list, dict]: ...
    def register(self, scope: ReadScope, prepared: PreparedContent, expected_generation: int) -> dict: ...
    def advance_context(self, scope: ReadScope, request_id: str, reason: str) -> int: ...


class TemplateStore(Protocol):
    def prepare(self) -> dict: ...


class ReadBudget(Protocol):
    def measure(self, result: dict, prepared: list, representation: str) -> tuple[int, int]: ...
